import {test,expect} from '@playwright/test'
test('create, edit, update progress, archive, persist and back up',async({page})=>{
 await page.goto('/')
 await page.getByRole('button',{name:'＋ 收录产品'}).click()
 await page.getByLabel('产品名称').fill('测试保湿面霜')
 await page.getByLabel('分类',{exact:true}).fill('我的面霜')
 await page.getByRole('button',{name:'保存产品'}).click()
 await expect(page.locator('article')).toContainText('测试保湿面霜')
 await page.getByRole('button',{name:'编辑',exact:true}).click()
 await page.getByLabel('产品名称').fill('改名后的面霜')
 await page.getByRole('button',{name:'保存产品'}).click()
 await page.getByRole('button',{name:'更新进度'}).click()
 await page.getByRole('slider').fill('50')
 await page.getByRole('button',{name:'保存余量，7 天后复查'}).click()
 await expect(page.locator('article')).toContainText('余量 50%')
 await page.reload()
 await expect(page.locator('article')).toContainText('改名后的面霜')
 await page.getByRole('button',{name:'更新进度'}).click()
 await page.getByRole('button',{name:'已经用完，收入空瓶档案'}).click()
 await page.getByRole('button',{name:'空瓶档案',exact:true}).click()
 await expect(page.locator('article')).toContainText('愿意回购')
 const download=page.waitForEvent('download');await page.getByRole('button',{name:'导出备份'}).click();expect((await download).suggestedFilename()).toMatch(/DPAO-backup/)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy()
})
test('legacy retro categories visible and corrupted data protected',async({page})=>{
 await page.goto('/')
 await page.evaluate(()=>localStorage.setItem('dpao_data_v4',JSON.stringify([{id:1,name:'历史产品',category:'历史补登',status:'empty',rating:'normal',emptyDate:'2026-01-01'}])))
 await page.reload();await page.getByRole('button',{name:'空瓶档案',exact:true}).click()
 await expect(page.locator('article')).toContainText('历史产品')
 await page.evaluate(()=>localStorage.setItem('dpao_data_v4','broken'))
 await page.reload();await expect(page.getByRole('alert')).toContainText('暂停保存')
 expect(await page.evaluate(()=>localStorage.getItem('dpao_data_v4'))).toBe('broken')
})
test('retro entry, restore and expiry warnings work',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/');await page.getByRole('button',{name:'空瓶档案',exact:true}).click()
 await page.getByRole('button',{name:'＋ 补登空瓶'}).click()
 await page.getByLabel('产品名称').fill('补登精华')
 await page.getByRole('button',{name:'保存产品'}).click()
 await expect(page.locator('article')).toContainText('补登精华')
 const backup={version:1,items:[{id:99,name:'已到期测试',status:'active',openedDate:'2020-01-01',expireDate:'2021-01-01',amount:25,category:'特殊分类',pao:'12M'}]}
 page.once('dialog',d=>d.accept())
 await page.locator('footer input[type=file]').setInputFiles({name:'backup.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(backup))})
 await page.getByRole('button',{name:'梳妆台',exact:true}).click()
 await expect(page.locator('article')).toContainText('已超期')
 await page.getByRole('button',{name:'更新进度'}).click()
 await page.getByRole('button',{name:'未用完，决定停用'}).click()
 await page.getByRole('button',{name:'空瓶档案',exact:true}).click()
 await expect(page.locator('article')).toContainText('已停止使用')
 expect(errors).toEqual([])
 await page.screenshot({path:'/workspace/attachments/dpao-mobile.png',fullPage:true})
})
